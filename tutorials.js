  // Split the inside of a call at its top-level commas (not the ones in quotes or brackets).
  function topLevel(text) {
    var parts = [], depth = 0, quote = '', start = 0;
    for (var i = 0; i < text.length; i++) {
      var ch = text[i];
      if (quote) { if (ch === '\\') i++; else if (ch === quote) quote = ''; continue; }
      if (ch === '"' || ch === "'") quote = ch;
      else if ('([{'.indexOf(ch) >= 0) depth++;
      else if (')]}'.indexOf(ch) >= 0) depth--;
      else if (ch === ',' && depth === 0) { parts.push(text.slice(start, i)); start = i + 1; }
    }
    if (text.trim()) parts.push(text.slice(start));
    return parts;
  }

  // One short sentence for each line of code, so the reader knows what every line does.
  function explain(line, next) {
    var t = line.trim(), m, e = EXPLAIN;
    if (!t || !e.comment) return '';
    function fill(text, values) { return text.replace(/\{(\w+)\}/g, function (_, key) { return values[key] === undefined ? '' : values[key]; }); }
    if (/^#!/.test(t)) return e.shebang;
    if (t[0] === '#') return e.comment;
    if (/^("""|\'\'\')/.test(t) || /^("""|\'\'\')$/.test(t)) return e.docString;
    if (/^[\]\)\}]+,?$/.test(t)) return e.closeBracket;
    if (/^if\s+__name__\s*==/.test(t)) return e.mainGuard;
    if (/^(sys\.)?exit\(/.test(t)) return e.exitCall;
    if (/\bsys\.argv\b/.test(t) && !/^(print|if)\b/.test(t)) return e.argvUse;
    if (/argparse\.ArgumentParser\(/.test(t)) return e.argparseMake;
    if (/\.add_argument\(/.test(t)) return e.argparseAdd;
    if (/\.parse_args\(/.test(t)) return e.argparseParse;
    if (/\bjson\.dumps\(/.test(t)) return e.jsonDumps;
    if (/^print\(/.test(t) && e.printText) {
      var inner = t.replace(/\)\s+#.*$/, ')').replace(/^print\(/, '').replace(/\)$/, '');
      var parts = topLevel(inner);
      if (parts.length === 1) {
        var only = parts[0].trim();
        var lit = only.match(/^(["'])([^"'\\{}]*)\1$/);
        if (lit) return fill(e.printText, {text: lit[2] || ' '});
        if (/^-?[\d.]+$/.test(only)) return fill(e.printText, {text: only});
        if (/^f["']/.test(only)) return e.printF;
        if (/^\w+$/.test(only) && !/^(True|False|None)$/.test(only)) return fill(e.printName, {name: only});
        if (only.length <= 40) return fill(e.printValue, {expr: only});
      } else if (parts.length > 1) {
        if (parts.some(function (p) { return /^\s*(sep|end)\s*=/.test(p); })) return e.printSep;
        return e.printMany;
      }
    }
    if (/^print\(/.test(t)) return e.print;
    if ((m = t.match(/^(\w+)\s*=\s*(float|int)\(input\((["'])([^"']*)\3\)\)\s*(#.*)?$/)) && e.askNumberIn) return fill(e.askNumberIn, {question: m[4].trim(), name: m[1]});
    if ((m = t.match(/^(\w+)\s*=\s*input\((["'])([^"']*)\2\)\s*(#.*)?$/)) && e.askIn) return fill(e.askIn, {question: m[3].trim(), name: m[1]});
    if (/^\w+\s*=\s*(float|int)\(input\(/.test(t)) return e.askNumber;
    if (/^[\w, ]+\s*=\s*input\(/.test(t)) return e.askNow;
    if (/^import\b|^from\b.*\bimport\b/.test(t)) return e.importIt;
    if (/^@/.test(t)) return e.decorator;
    if ((m = t.match(/^if\s+(.+?):\s*(#.*)?$/)) && m[1].length <= 32 && e.ifThis) return fill(e.ifThis, {cond: m[1]});
    if ((m = t.match(/^elif\s+(.+?):\s*(#.*)?$/)) && m[1].length <= 32 && e.elifThis) return fill(e.elifThis, {cond: m[1]});
    if (/^if\b/.test(t)) return e.ifBlock;
    if (/^elif\b/.test(t)) return e.elifBlock;
    if (/^else\s*:/.test(t)) return e.elseBlock;
    if ((m = t.match(/^for\s+(\w+)\s+in\s+range\(\s*(-?\d+)\s*(?:,\s*(-?\d+)\s*)?(?:,\s*(-?\d+)\s*)?\):\s*$/)) && e.forValues) {
      var a = m[3] === undefined ? 0 : Number(m[2]), b = m[3] === undefined ? Number(m[2]) : Number(m[3]), stepBy = m[4] === undefined ? 1 : Number(m[4]), values = [];
      for (var v = a; stepBy > 0 ? v < b : v > b; v += stepBy) { values.push(v); if (values.length > 6) break; }
      if (stepBy !== 0 && values.length && values.length <= 6) return fill(e.forValues, {name: m[1], values: values.join(', ')});
      if (stepBy === 1 && values.length) return fill(e.forFromTo, {name: m[1], first: a, last: b - 1});
    }
    if ((m = t.match(/^for\s+(\w+)\s+in\s+([\w.]+|"[^"]*"|'[^']*'):\s*$/)) && e.forEachIn) return fill(e.forEachIn, {name: m[1], seq: m[2]});
    if (/^for\b.*\brange\(/.test(t)) return e.forRange;
    if (/^for\b/.test(t)) return e.forLoop;
    if (/^while\s+True\b/.test(t)) return e.whileForever;
    if ((m = t.match(/^while\s+(.+?):\s*(#.*)?$/)) && m[1].length <= 32 && e.whileThis) return fill(e.whileThis, {cond: m[1]});
    if (/^while\b/.test(t)) return e.whileLoop;
    if ((m = t.match(/^async\s+def\s+(\w+)/))) return fill(e.asyncDef, {name: m[1]});
    if (/^await\b/.test(t)) return e.awaitIt;
    if (/^def\s+__init__\b/.test(t)) return e.initDef;
    if (/^def\s+__\w+__\b/.test(t)) return e.specialDef;
    if ((m = t.match(/^def\s+(\w+)/))) return fill(/^def\s+\w+\(\s*self\b/.test(t) ? e.methodDef : e.fnDef, {name: m[1]});
    if ((m = t.match(/^class\s+(\w+)\s*\((\w+)\)/))) return fill(e.classInherit, {name: m[1], parent: m[2]});
    if ((m = t.match(/^class\s+(\w+)/))) return fill(e.classDef, {name: m[1]});
    if ((m = t.match(/^return\s+(.+?)\s*(#.*)?$/)) && m[1].length <= 30 && e.returnThis) return fill(e.returnThis, {value: m[1]});
    if (/^return\b/.test(t)) return e.returnIt;
    if (/^yield\b/.test(t)) return e.yieldIt;
    if (/^break\b/.test(t)) return e.breakIt;
    if (/^continue\b/.test(t)) return e.continueIt;
    if (/^pass\b/.test(t)) return e.passIt;
    if (/^try\s*:/.test(t)) return e.tryBlock;
    if (/^except\b/.test(t)) return e.exceptBlock;
    if (/^finally\s*:/.test(t)) return e.finallyBlock;
    if (/^raise\b/.test(t)) return e.raiseIt;
    if (/^with\b/.test(t)) return e.withBlock;
    if (/^assert\b/.test(t)) return e.assertIt;
    if (/^del\b/.test(t)) return e.delIt;
    if (/^(global|nonlocal)\b/.test(t)) return e.globalIt;
    if (/^match\b/.test(t)) return e.matchBlock;
    if (/^case\b/.test(t)) return e.caseBlock;
    if ((m = t.match(/^([\w.]+(?:\[[^\]]+\])?)\s*(\+|-|\*)=\s*([^=].{0,24}?)\s*(#.*)?$/)) && e.addTo) return fill({'+': e.addTo, '-': e.takeFrom, '*': e.timesBy}[m[2]], {name: m[1], value: m[3]});
    if (/^[\w.\[\]"']+\s*(\+|-|\*|\/|\/\/|%|\*\*)=/.test(t)) return e.augAssign;
    if (/^[\w.]+\s*=\s*lambda\b/.test(t)) return e.lambdaDef;
    if (/^[\w.]+\s*=\s*[\[\{(].*\bfor\b.*\bin\b/.test(t)) return e.comprehension;
    if ((m = t.match(/^(\w+)\s*=\s*\[(.*)\]\s*$/)) && e.listOf && !/[\[\](]/.test(m[2])) {
      var items = m[2].trim() ? topLevel(m[2]).length : 0;
      return items ? fill(e.listOf, {name: m[1], count: items}) : fill(e.listEmpty, {name: m[1]});
    }
    if (/^[\w.]+\s*=\s*\[\s*$/.test(t) || /^[\w.]+\s*=\s*\[.*\]\s*$/.test(t)) return e.listLiteral;
    if (/^[\w.]+\s*=\s*\{\s*$/.test(t) || /^[\w.]+\s*=\s*\{.*\}\s*$/.test(t)) return /^[\w.]+\s*=\s*\{\s*\}\s*$/.test(t) || /:/.test(t) || /\{\s*$/.test(t) ? e.dictLiteral : e.setLiteral;
    if (/^[\w.]+\s*=\s*\(.*,.*\)\s*$/.test(t) && !/\w\(/.test(t.replace(/^[\w.]+\s*=\s*/, '').slice(1))) return e.tupleLiteral;
    if (/^[\w.]+\[.+\]\s*=/.test(t)) return e.itemAssign;
    if (/^[\w.]+\.\w+\s*=[^=]/.test(t) && !/,/.test(t.split('=')[0])) return e.attrAssign;
    if (/^[\w.]+\s*,\s*[\w., *]+=[^=]/.test(t) || /^\(.*\)\s*,.*=[^=]/.test(t)) return e.unpackAssign;
    if ((m = t.match(/^(\w+)\s*=\s*(.+)$/)) && e.assignValue) {
      var value = m[2].trim(), named = m[1];
      if (/^("""|''')/.test(value) && e.assignLong) return fill(e.assignLong, {name: named});
      if (/^[A-Za-z_]\w*$/.test(value) && !/^(True|False|None)$/.test(value) && e.assignSame) return fill(e.assignSame, {name: named, value: value});
      if (new RegExp('\\b' + named + '\\b').test(value) && value.length <= 30) return fill(e.assignUpdate, {name: named, value: value});
      if ((/^("[^"]*"|'[^']*'|-?[\d.]+|True|False|None)$/.test(value)) && value.length <= 30) return fill(e.assignValue, {name: named, value: value});
      var call = value.match(/^([\w.]+)\(/);
      if (call && !/^[A-Z]/.test(call[1]) && value.length <= 60) return fill(e.assignCall, {name: named, fn: call[1]});
      if (call && /^[A-Z]/.test(call[1].split('.').pop())) return fill(e.assignObject, {name: named, cls: call[1].split('.').pop()});
      if (!/[(\[{]/.test(value) && value.length <= 30) return fill(e.assignSum, {name: named, value: value});
    }
    if ((m = t.match(/^(\w+)\s*(?::\s*[\w\[\], ]+)?=\s*/))) return fill(e.assign, {name: m[1]});
    if (/^\w+\s*:\s*[\w\[\], |.]+$/.test(t)) return e.fieldDef;
    if (/^[\w.\[\]"' ]+\s(in|not in|==|!=|<|>|<=|>=)\s[\w.\[\]"' ]+$/.test(t)) return e.compareIt;
    if (/^"[^"]*"\s*:|^'[^']*'\s*:|^\d+\s*:/.test(t)) return e.dictEntry;
    if ((m = t.match(/^([\w.\[\]"']+)\.(\w+)\(/))) return fill(e.callMethod, {obj: m[1], method: m[2]});
    if ((m = t.match(/^(\w+)\(/))) return fill(e.callFn, {name: m[1]});
    if (/^[\w"'\d(\[{-]/.test(t) && /,$/.test(t)) return e.listItem;
    if (/^[\w.]+$/.test(t)) return e.showValue;
    return '';
  }
  // The notes of a whole program: a line inside a long text between triple quotes is part of that text.
  function explainCode(code) {
    var rows = code.split('\n'), inside = false, notes = [];
    rows.forEach(function (line, i) {
      var quotes = (line.match(/"""|\'\'\'/g) || []).length;
      var startsInside = inside;
      if (quotes % 2 === 1) inside = !inside;
      if (startsInside) notes.push(EXPLAIN.insideText || '');
      else if (quotes % 2 === 1 && !/^\s*("""|\'\'\')/.test(line)) notes.push(explain(line.replace(/("""|\'\'\').*$/, '$1'), rows[i + 1]) || EXPLAIN.docString);
      else notes.push(explain(line, rows[i + 1]));
    });
    return notes;
  }
